/**
 * v9: immutable usage ledger.
 *  - New `usage_events` table — one row per completed assistant turn,
 *    capturing tokens / cost / model at completion time. Deliberately
 *    not a foreign key to `messages` so deleting a chat doesn't rewrite
 *    historical usage totals.
 *  - Backfill from existing assistant messages. Deterministic event id
 *    (`evt-{messageId}`) makes the backfill idempotent — re-running on
 *    every launch is a no-op once events exist.
 */
function applyMigrationV9() {
  sqlite.execSync(`
    CREATE TABLE IF NOT EXISTS usage_events (
      id text PRIMARY KEY NOT NULL,
      model_id text NOT NULL,
      provider text NOT NULL,
      prompt_tokens integer NOT NULL,
      completion_tokens integer NOT NULL,
      cost_usd real NOT NULL,
      created_at integer NOT NULL,
      message_id text
    );
  `)
  // Backfill: copy every assistant message that has token data into the
  // ledger. INSERT OR IGNORE on a deterministic id makes this safe to
  // re-run — the migration ladder fires on every launch.
  sqlite.execSync(`
    INSERT OR IGNORE INTO usage_events (
      id, model_id, provider, prompt_tokens, completion_tokens,
      cost_usd, created_at, message_id
    )
    SELECT
      'evt-' || messages.id,
      COALESCE(model_id, 'unknown'),
      COALESCE(provider, 'openrouter'),
      prompt_tokens,
      completion_tokens,
      COALESCE(cost_usd, 0),
      created_at,
      id
    FROM messages
    WHERE role = 'assistant'
      AND prompt_tokens IS NOT NULL
      AND completion_tokens IS NOT NULL;
  `)
}

let migrated = false

function applyMigrations() {
  if (migrated) return
  sqlite.execSync(MIGRATION_V1)
  applyMigrationV2()
  applyMigrationV3()
  applyMigrationV4()
  applyMigrationV5()
  applyMigrationV6()
  applyMigrationV7()
  applyMigrationV8()
  applyMigrationV9()
  migrated = true
}

/**
 * Drop-in replacement for drizzle's `useMigrations(db, migrations)` — same
 * `{ success, error }` contract so the root layout migration gate doesn't
 * need to change.
 */
export function useRunMigrations(): {
  success: boolean
  error: Error | undefined
} {
  const [state, setState] = useState<{ success: boolean; error: Error | undefined }>(
    { success: migrated, error: undefined },
  )

  useEffect(() => {
    if (state.success) return
    try {
      applyMigrations()
      setState({ success: true, error: undefined })
    } catch (e) {
      setState({
        success: false,
        error: e instanceof Error ? e : new Error("Migration failed"),
      })
    }
  }, [state.success])

  return state
}
